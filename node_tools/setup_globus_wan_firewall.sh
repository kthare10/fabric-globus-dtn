#!/usr/bin/env bash
# setup_globus_wan_firewall.sh - let only Globus in on the DTN's public interface.
#
# A facility-port DTN puts a public IPv4 and IPv6 address on its data NIC, and
# everything listening on all addresses - sshd above all - answers there too.
# Globus Connect Server needs exactly two things inbound:
#   443/tcp          GCS Manager API and the HTTPS front end
#   50000-51000/tcp  GridFTP data channels
#
# This installs one nftables table that matches ONLY the public interface. It
# is deliberately not firewalld: firewalld's default zone would also govern the
# management NIC (the session that runs this) and any FABNet NIC.
# Here those two are never matched, so a mistake can cost the public side at
# worst, never management.
#
# Allowed in on <iface>: replies to the DTN's own connections, the ICMP that
# IPv6 needs to function at all (neighbour discovery) and that both families
# need for path MTU discovery, and the Globus ports. Everything else is dropped.
#
# Persisted as a systemd unit ordered before the network comes up, so the
# addresses are never reachable unprotected after a reboot. Safe to re-run.
#
# Usage:
#   sudo ./setup_globus_wan_firewall.sh --iface eth1 [--ports 443,50000-51000]
#   sudo ./setup_globus_wan_firewall.sh --remove
set -euo pipefail

IFACE=""; PORTS="443,50000-51000"; REMOVE=0
CONF=/etc/globus-dtn/wan-firewall.nft
UNIT=/etc/systemd/system/globus-wan-firewall.service
TABLE=globus_wan

while [ $# -gt 0 ]; do
  case "$1" in
    --iface)  IFACE="$2"; shift 2;;
    --ports)  PORTS="$2"; shift 2;;
    --remove) REMOVE=1; shift;;
    -h|--help) grep '^#' "$0" | sed 's/^# \{0,1\}//'; exit 0;;
    *) echo "unknown argument: $1" >&2; exit 2;;
  esac
done

[ "$(id -u)" -eq 0 ] || { echo "ERROR: must run as root (use sudo)" >&2; exit 2; }
command -v nft >/dev/null || dnf install -y -q nftables >/dev/null

if [ "$REMOVE" -eq 1 ]; then
  systemctl disable --now globus-wan-firewall.service >/dev/null 2>&1 || true
  nft delete table inet "$TABLE" 2>/dev/null || true
  rm -f "$UNIT" "$CONF"; systemctl daemon-reload
  echo "removed: the public interface is unfiltered again"
  exit 0
fi

[ -n "$IFACE" ] || { echo "ERROR: --iface is required" >&2; exit 2; }
ip link show "$IFACE" >/dev/null 2>&1 || { echo "ERROR: no interface $IFACE" >&2; exit 2; }
# The interface the session came in on must never be the one filtered.
if [ -n "${SSH_CONNECTION:-}" ]; then
  SRC_DEV="$(ip route get "$(echo "$SSH_CONNECTION" | awk '{print $1}')" 2>/dev/null \
             | grep -o 'dev [^ ]*' | awk '{print $2}' | head -1)"
  if [ "$SRC_DEV" = "$IFACE" ]; then
    echo "ERROR: this session reaches the host through $IFACE - filtering it would cut you off" >&2
    exit 2
  fi
fi
case "$PORTS" in *[!0-9,-]*|"") echo "ERROR: --ports must look like 443,50000-51000" >&2; exit 2;; esac
PORTSET="$(echo "$PORTS" | sed 's/,/, /g')"

install -d -m 0755 "$(dirname "$CONF")"
# Declaring the table before flushing it makes the file loadable whether or not
# the table already exists, so a re-run replaces the rules instead of adding to them.
cat > "$CONF" <<EOF
# Generated by setup_globus_wan_firewall.sh - only $IFACE is matched.
table inet $TABLE {}
flush table inet $TABLE
table inet $TABLE {
  chain input {
    type filter hook input priority filter; policy accept;
    iifname != "$IFACE" accept
    ct state established,related accept
    ct state invalid drop
    # Neighbour discovery, router adverts and packet-too-big: IPv6 breaks without them.
    meta l4proto ipv6-icmp accept
    icmp type { echo-request, destination-unreachable, time-exceeded } accept
    tcp dport { $PORTSET } accept
    counter drop
  }
}
EOF
chmod 0644 "$CONF"
nft -c -f "$CONF"          # syntax check before anything is live
nft -f "$CONF"

cat > "$UNIT" <<EOF
[Unit]
Description=Allow only Globus in on the DTN public interface ($IFACE)
DefaultDependencies=no
Before=network-pre.target
Wants=network-pre.target

[Service]
Type=oneshot
RemainAfterExit=yes
ExecStart=/usr/sbin/nft -f $CONF
ExecStop=/usr/sbin/nft delete table inet $TABLE

[Install]
WantedBy=multi-user.target
EOF
systemctl daemon-reload
systemctl enable globus-wan-firewall.service >/dev/null 2>&1
systemctl start globus-wan-firewall.service

echo "== $IFACE now accepts only: tcp $PORTSET, replies, and required ICMP"
nft list table inet "$TABLE"
echo "unit: $(systemctl is-enabled globus-wan-firewall.service) / $(systemctl is-active globus-wan-firewall.service)"
